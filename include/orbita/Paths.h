#pragma once

#include <QString>

namespace orbita::paths {

/// Единые места хранения и настраиваемые параметры.
///
/// Читаются здесь, а пишутся окном настроек: так консольная часть, плагины
/// Dolphin и интерфейс всегда смотрят в одно и то же место, даже если
/// пользователь сменил точку подключения.

QString dataDir();
QString databaseFile();
QString cacheDir();
/// Миниатюры отдельно от содержимого: они мелкие и восстановимые,
/// им незачем вытесняться вместе с настоящими файлами.
QString thumbsDir();

/// Куда подключается Диск. По умолчанию ~/Яндекс.Диск.
QString mountPoint();
/// Куда складываются файлы, отправленные из файлового менеджера.
/// По умолчанию «/Загрузки» — как у официального клиента.
QString uploadFolder();
/// Потолок кэша содержимого в байтах.
qint64 cacheBudget();
/// Как часто спрашивать Диск о новинках, в секундах.
int pollSeconds();

/// Файл настроек, который читают все части клиента.
QString settingsFile();

} // namespace orbita::paths
